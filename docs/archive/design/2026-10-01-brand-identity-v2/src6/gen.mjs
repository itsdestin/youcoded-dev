// gen.mjs — writes art.js: every posed mascot the boards need, in every palette, as SVG strings.
// The boards (boards.html) lay them out against real letters in the browser, where the fonts
// and letter positions are known. Run: node gen.mjs
import fs from 'fs';
import { mascot } from './mascot.mjs';

// Poses, each a rotation set about the rig's pivots (see mascot.mjs). Names say what it's doing.
const POSES = {
  stand:  { pose: 'welcome', face: 'welcome' },                          // today's icon pose
  punch:  { arms: [35, -90], legs: [16, -16], face: 'curious' },          // right fist out, left arm back
  uppercut:{ arms: [40, -115], legs: [22, -10], face: 'curious' },        // fist up into the Y, feet off the ground
  peek:   { peek: true, face: 'welcome' },                               // mitts on a ledge
  sitwave:{ pose: 'welcome', face: 'happy' },
  cheer:  { pose: 'cheer', face: 'happy' },
  armsout:{ arms: [90, -90], legs: [0, 0], face: 'happy' },               // a hand to each side
  hop:    { arms: [40, -40], legs: [24, -24], face: 'happy' },
  hang:   { arms: [25, -180], legs: [14, -6], face: 'happy' },            // right arm straight up
  hangL:  { arms: [180, -30], legs: [8, -16], face: 'happy' },          // left arm straight up
  carry:  { arms: [-28, 28], legs: [12, -12], face: 'welcome' },          // arms in, holding something
  ride:   { arms: [150, -150], legs: [30, -30], face: 'happy' },
  dive:   { arms: [165, -165], legs: [-12, 12], face: 'shocked' },        // arms up, falling
};
// Palettes: the shipped purple, plus three themes' colours for the "dressed in other themes" row.
export const PAL = {
  purple:     {},
  golden:     { acc: '#E9A21F', light: '#FFD268', shade: '#B8760F', edge: '#5A3A08' },
  meadow:     { acc: '#4E9A6E', light: '#8FD1A8', shade: '#2F6B4A', edge: '#163A26' },
  strawberry: { acc: '#FFFFFF', light: '#FFFFFF', shade: '#F1CFD8', edge: '#3A1420', faceInk: '#3A1420' },
};
const out = {};
for (const [pk, colors] of Object.entries(PAL)) for (const [k, o] of Object.entries(POSES)) {
  const hat = pk === 'strawberry' ? 'kitty-ears' : null;
  out[`${k}.${pk}`] = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-3 -5 30 30">${mascot({ ...o, colors, hat })}</svg>`;
}
fs.writeFileSync('art.js', '// generated by gen.mjs — do not edit\nconst ART = ' + JSON.stringify(out) + ';\n');
console.log(Object.keys(out).length, 'mascots,', (fs.statSync('art.js').size / 1024 | 0) + 'KB');
