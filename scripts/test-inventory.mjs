#!/usr/bin/env node
// Test-suite inventory for the 2026-09-16 CI/test health follow-ups.
//
// WHY a script and not a table typed once: the tables the consolidation and the
// source-grep sweep work from (which test files cluster by name, which source
// module each one really tests, which files read source as text) go stale the
// week after they are written — 168 test files were added in one week. Re-run
// this and the plan's data is current again.
//
// Usage: node scripts/test-inventory.mjs [<checkout>/desktop] > docs/active/plans/2026-09-16-test-inventory.md
import fs from 'node:fs';
import path from 'node:path';

const desktop = path.resolve(process.argv[2] ?? path.join(process.cwd(), 'youcoded', 'desktop'));
const testsDir = path.join(desktop, 'tests');

function walk(dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (e.name !== '__mocks__' && e.name !== 'fixtures' && e.name !== 'helpers') out.push(...walk(p)); }
    else if (/\.test\.tsx?$/.test(e.name)) out.push(p);
  }
  return out.sort();
}
const files = walk(testsDir);
const rel = (p) => path.relative(desktop, p).split(path.sep).join('/');
const lines = (p) => fs.readFileSync(p, 'utf8').split('\n').length;
const cases = (src) => (src.match(/^\s*(it|test)(\.skipIf\([^)]*\)|\.skip|\.only|\.each\([^)]*\))?\(/gm) ?? []).length;

// --- 1. what each test file imports from src/ (the module it really tests)
const importRe = /(?:from\s+|import\(|vi\.mock\(\s*)['"]((?:\.\.\/)+src\/[^'"]+)['"]/g;
const byFile = new Map();   // rel test -> { lines, cases, modules: [] }
const byModule = new Map(); // src module -> [rel tests]
for (const f of files) {
  const src = fs.readFileSync(f, 'utf8');
  const mods = new Set();
  for (const m of src.matchAll(importRe)) {
    const abs = path.resolve(path.dirname(f), m[1]);
    const r = path.relative(desktop, abs).split(path.sep).join('/').replace(/\.(tsx?|js)$/, '');
    mods.add(r);
  }
  const rec = { lines: lines(f), cases: cases(src), modules: [...mods] };
  byFile.set(rel(f), rec);
  for (const m of mods) { if (!byModule.has(m)) byModule.set(m, []); byModule.get(m).push(rel(f)); }
}

// --- 2. filename clusters (first token of the basename)
const clusters = new Map();
for (const f of files) {
  const base = path.basename(f).replace(/\.test\.tsx?$/, '');
  const tok = base.split('-')[0];
  if (!clusters.has(tok)) clusters.set(tok, []);
  clusters.get(tok).push(rel(f));
}

// --- 3. files that read source as text
const grepRe = [
  /readStripped|helpers\/guard-scope/,
  /__dirname,\s*'\.\.',?\s*'(\.\.|src|shared|scripts|docs|assets|hook-scripts)'/,
  /__dirname,\s*'\.\.\/(\.\.\/)?(src|shared|scripts|docs|assets|package|electron)/,
  /__dirname\}\/\.\.\/(\.\.\/)?(src|shared|scripts|docs)/,
  /electron-builder\.yml/,
  /new URL\('\.\.\/(\.\.\/)?(src|shared|scripts|docs|package|electron)/,
  /(cwd\(\)|resolve)\([^)]*'(\.\.\/)*(src|shared|scripts|docs)\//,
  // WHY the four below (2026-09-17): the literal patterns above only see a path
  // spelled out at the read site. The Task 7 review found a dozen tests that
  // read source through a small helper, where the path arrives as a variable —
  // `read('../src/x.ts')` over `readFileSync(new URL(rel, import.meta.url))` or
  // `path.join(__dirname, '..', rel)` — and so were missing from section 3.
  // Each pattern needs the variable to sit where a SOURCE path goes (under the
  // desktop root), so tests that read their own temp dirs or fixtures stay out.
  /readFileSync\(\s*new URL\(\s*[A-Za-z_$]/,            // readFileSync(new URL(rel, import.meta.url))
  /new URL\(\s*'\.\.\/?'\s*,\s*import\.meta\.url/,       // the desktop root as a URL, then a folder walk
  /__dirname,\s*'\.\.',\s*(\.\.\.)?[A-Za-z_$]/,          // join(__dirname, '..', rel) / (…, ...parts)
  /readFileSync\(\s*(path\.)?(join|resolve)\(\s*[A-Z_]*ROOT\s*,/, // readFileSync(join(ROOT, rel))
];
const sourceGrep = files.filter((f) => { const s = fs.readFileSync(f, 'utf8'); return grepRe.some((r) => r.test(s)); }).map(rel);

// --- output
const out = [];
out.push('# Test inventory — generated by `node scripts/test-inventory.mjs`, do not edit by hand');
out.push('');
out.push(`Generated ${new Date().toISOString().slice(0, 10)} from ${rel(testsDir)}: ${files.length} test files, ${[...byFile.values()].reduce((a, b) => a + b.cases, 0)} cases, ${[...byFile.values()].reduce((a, b) => a + b.lines, 0)} lines.`);
out.push('');
out.push('## 1. Filename clusters (4 or more files sharing the first token) — the consolidation order, largest first');
out.push('');
const big = [...clusters.entries()].filter(([, v]) => v.length >= 4).sort((a, b) => b[1].length - a[1].length);
for (const [tok, list] of big) {
  const total = list.reduce((a, f) => a + byFile.get(f).lines, 0);
  out.push(`### \`${tok}-\` — ${list.length} files, ${total} lines`);
  for (const f of list) { const r = byFile.get(f); out.push(`- \`${f}\` (${r.lines} lines, ${r.cases} cases) → ${r.modules.slice(0, 3).map((m) => '`' + m + '`').join(', ') || '_no src import_'}`); }
  out.push('');
}
out.push('## 2. Source modules tested by two or more files — each group is one target file');
out.push('');
const shared = [...byModule.entries()].filter(([, v]) => v.length >= 2).sort((a, b) => b[1].length - a[1].length);
for (const [m, list] of shared) {
  out.push(`### \`${m}\` — ${list.length} files`);
  for (const f of list) out.push(`- \`${f}\` (${byFile.get(f).lines} lines)`);
  out.push('');
}
out.push('## 3. Files that read source or config as text (the sweep list)');
out.push('');
for (const f of sourceGrep) out.push(`- \`${f}\` (${byFile.get(f).lines} lines, ${byFile.get(f).cases} cases)`);
out.push('');
out.push(`Total: ${sourceGrep.length} files.`);
process.stdout.write(out.join('\n') + '\n');
