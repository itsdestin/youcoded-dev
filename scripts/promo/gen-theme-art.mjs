// Turns public/themes/<slug>/ (written by theme-assets.sh) into
// src/theme-art.generated.ts: every theme's mascot rig as an inline SVG string
// plus its companions (the sun, motes, sparks that float around the mascot in
// the app), read from the manifest. WHY a generated module and not <Img>: the
// host's arms, faces and hops are CSS transforms on NAMED PARTS of the rig, and
// an <img> has no parts — the SVG has to be inline in the DOM. The file is
// gitignored like public/; theme-assets.sh runs this last.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, 'public', 'themes');
const out = ['// GENERATED by gen-theme-art.mjs from public/themes/ — do not edit; run theme-assets.sh.',
  'export type Companion = { svg: string; size: number; aspect: number; ghost: boolean; dx: number; dy: number; float: number; floatMs: number };',
  'export const RIGS: Record<string, string> = {};', 'export const COMPANIONS: Record<string, Companion[]> = {};'];
for (const slug of readdirSync(ROOT).sort()) {
  const dir = join(ROOT, slug);
  const m = JSON.parse(readFileSync(join(dir, 'manifest.json'), 'utf8'));
  if (existsSync(join(dir, 'mascot-rig.svg'))) out.push(`RIGS[${JSON.stringify(slug)}] = ${JSON.stringify(readFileSync(join(dir, 'mascot-rig.svg'), 'utf8'))};`);
  const comps = (m.companions ?? []).map((c) => {
    const file = join(dir, 'companions', c.asset.split('/').pop());
    const svg = readFileSync(file, 'utf8');
    // `size` is the companion's WIDTH relative to the mascot; its height follows the
    // SVG's own viewBox (Halftone's bars are 100×6 — drawn square they were a solid
    // box on the mascot's head). A 'ghost' (Halftone's chromatic after-image) is
    // invisible at rest in the app and fades in with motion; the video does the same.
    const vb = /viewBox="([^"]+)"/.exec(svg)?.[1].trim().split(/\s+/).map(Number) ?? [0, 0, 1, 1];
    const aspect = vb[2] / vb[3];
    return { svg, size: c.size, aspect, ghost: /ghost/i.test(c.asset), dx: c.dx, dy: c.dy, float: c.float ?? 0.03, floatMs: c.floatMs ?? 2400 };
  });
  if (comps.length) out.push(`COMPANIONS[${JSON.stringify(slug)}] = ${JSON.stringify(comps)};`);
}
writeFileSync(join(HERE, 'src', 'theme-art.generated.ts'), out.join('\n') + '\n');
console.log(`[gen-theme-art] wrote src/theme-art.generated.ts`);
