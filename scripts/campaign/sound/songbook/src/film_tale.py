# ---- the tune, phrase by phrase
# WHY the cell spread over her breath, entering off the beat (2.5) and tied over the bar line:
# the brand is heard once, small and interrupted, the way a thought is while someone talks.
# B-flat 4 is the only note in her range and it starts inside her breath after "technology.";
# the F5 waits for her pause after "do," (a 3-quarter-beat tie) instead of landing on her word.
